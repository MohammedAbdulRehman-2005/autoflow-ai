# ENUMS
# ─────────────────────────────────────────────────────────────────────────────

class TriggerType(str, Enum):
    schedule  = "schedule"    # Cron-based scheduling (APScheduler)
    webhook   = "webhook"     # Incoming HTTP POST to /hooks/{workflow_id}
    manual    = "manual"      # Triggered by user or API call
    event     = "event"       # Internal AutoFlow event bus


class NodeType(str, Enum):
    trigger     = "trigger"       # Entry point — exactly one per workflow
    action      = "action"        # Performs an external operation
    condition   = "condition"     # Branches flow based on a boolean expression
    delay       = "delay"         # Pauses execution for a duration
    loop        = "loop"          # Iterates over a list of items
    ai_agent    = "ai_agent"      # Calls an LLM for reasoning or text generation
    transformer = "transformer"   # Reshapes/maps data between nodes


