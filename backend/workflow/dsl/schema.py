"""
AutoFlow AI X — Workflow DSL Pydantic Schema
=============================================

The DSL (Domain-Specific Language) is the canonical, executable representation
of a workflow inside AutoFlow AI X. Every workflow — whether generated by the
AI planner, built in the visual editor, or created via API — is stored and
executed as a DSL JSON object.

Template variable syntax: {{node_id.output.field}}, {{trigger.payload.field}},
                           {{context.today}}, {{env.VAR_NAME}}
"""

import re
import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Literal, Optional, Union

from pydantic import BaseModel, Field, field_validator, model_validator


