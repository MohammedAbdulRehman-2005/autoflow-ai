# ─────────────────────────────────────────────────────────────────────────────
# ERROR POLICY  (RFC-002 §3 Error Boundaries)
# ─────────────────────────────────────────────────────────────────────────────

class ErrorPolicy(str, Enum):
    """
    Per-node error policy — governs what happens when a node fails.

    Interaction with on_failure routing (important — these are different things):
      - "stop"     : The workflow halts immediately regardless of on_failure.
                     on_failure is ignored. The run is marked FAILED.
      - "continue" : The node is marked failed but the workflow continues.
                     Execution routes to on_failure if set; otherwise on_success.
                     Use when a failed node is non-blocking (e.g. a notification).
      - "retry"    : Uses retry_policy (max_attempts, backoff). If all attempts
                     are exhausted, falls through to on_failure like "continue".
                     If retry_policy is absent, behaves like "stop" after 1 attempt.

    Note: this field applies to full workflow runs only.
    Execute Step in the Node Inspector always uses a single attempt ("stop" semantics).
    """
    stop     = "stop"
    continue_ = "continue"   # underscore avoids clash with Python keyword
    retry    = "retry"



class ScheduleTriggerConfig(BaseModel):
    cron: str = Field(..., description="Cron expression e.g. '0 9 * * *'")
    timezone: str = Field(default="UTC")

    @field_validator("cron")
    @classmethod
    def validate_cron(cls, v: str) -> str:
        parts = v.strip().split()
        if len(parts) not in (5, 6):
            raise ValueError(f"Invalid cron expression '{v}': must have 5 or 6 fields.")
        return v


class WebhookTriggerConfig(BaseModel):
    path: Optional[str] = Field(None, description="Custom webhook path slug")
    secret: Optional[str] = Field(None, description="HMAC signature secret for verification")
    method: str = Field(default="POST")


class ManualTriggerConfig(BaseModel):
    description: Optional[str] = None


class EventTriggerConfig(BaseModel):
    event_name: str = Field(..., description="Internal AutoFlow event name to listen for")
    filters: Optional[Dict[str, Any]] = None


class TriggerConfig(BaseModel):
    type: TriggerType
    config: Union[
        ScheduleTriggerConfig,
        WebhookTriggerConfig,
        ManualTriggerConfig,
        EventTriggerConfig,
        Dict[str, Any],   # fallback for LLM-generated configs
    ] = Field(default_factory=dict)


# ─────────────────────────────────────────────────────────────────────────────
# RETRY POLICY
# ─────────────────────────────────────────────────────────────────────────────

class RetryPolicy(BaseModel):
    max_attempts: int = Field(default=3, ge=1, le=10)
    backoff_seconds: int = Field(default=60, ge=0)
    backoff_multiplier: float = Field(default=2.0, ge=1.0)


# ─────────────────────────────────────────────────────────────────────────────
# WORKFLOW NODE
# ─────────────────────────────────────────────────────────────────────────────

class WorkflowNodeDSL(BaseModel):
    id: str = Field(
        ...,
        description="Unique node ID within this workflow. Use snake_case (e.g. 'send_email_1').",
        pattern=r"^[a-z][a-z0-9_]*$",
    )
    type: NodeType
    service: ServiceType
    operation: OperationType
    label: str = Field(..., description="Human-readable name shown in the visual editor")

    # Template-variable-aware parameters specific to this operation
    params: Dict[str, Any] = Field(
        default_factory=dict,
        description=(
            "Operation-specific parameters. Supports template vars: "
            "{{node_id.output.field}}, {{trigger.payload.field}}, {{context.today}}, {{env.VAR}}"
        ),
    )

    # Credential reference — resolved by CredentialResolver at runtime (RFC-001 §8)
    # Optional in Sprint 1; populated by Node Inspector in Sprint 2.
    credential_id: Optional[str] = Field(
        None,
        description="Named credential ID; resolved by CredentialResolver at runtime.",
    )

    # Routing
    on_success: Optional[str] = Field(
        None,
        description="Node ID to route to when this node completes successfully.",
    )
    on_failure: Optional[str] = Field(
        None,
        description="Node ID to route to when this node fails. Null = stop and mark run failed.",
    )

    # Optional per-node overrides
    retry_policy: Optional[RetryPolicy] = None
    timeout_seconds: Optional[int] = Field(None, ge=1, le=3600)
    is_disabled: bool = Field(default=False)

    # ── Sprint 2 Settings fields (Node Inspector Settings tab) ────────────────
    # All fields are optional and backward-compatible — existing stored DSLs
    # without these fields will parse correctly using the defaults below.

    error_policy: ErrorPolicy = Field(
        default=ErrorPolicy.stop,
        description=(
            "What to do when this node fails. "
            "'stop' halts the workflow; 'continue' routes to on_failure; "
            "'retry' uses retry_policy then routes to on_failure."
        ),
    )

    always_output_data: bool = Field(
        default=False,
        description=(
            "If True, pass output downstream even if the node failed. "
            "No-op in Execute Step context (single-node isolation run)."
        ),
    )

    execute_once: bool = Field(
        default=False,
        description=(
            "If True, skip this node if it has already run successfully in this run_id. "
            "No-op in Execute Step context (single-node isolation run)."
        ),
    )

    notes: Optional[str] = Field(
        default=None,
        max_length=4000,
        description="Free-text notes about this node. Shown in Inspector and optionally on canvas.",
    )

    display_note_in_flow: bool = Field(
        default=False,
        description="If True, show a notes badge on this node's canvas card.",
    )

    @field_validator("id")
    @classmethod
    def id_no_reserved_names(cls, v: str) -> str:
        reserved = {"start", "end", "true", "false", "null", "none"}
        if v.lower() in reserved:
            raise ValueError(f"Node ID '{v}' is a reserved keyword.")
        return v


# ─────────────────────────────────────────────────────────────────────────────
# WORKFLOW EDGE
# ─────────────────────────────────────────────────────────────────────────────

class WorkflowEdgeDSL(BaseModel):
    source_id: str = Field(..., description="ID of the source node")
    target_id: str = Field(..., description="ID of the target node")
    label: Optional[str] = Field(
        None,
        description="Edge label shown on canvas. For condition nodes: 'true' | 'false' | custom.",
    )
    condition: Optional[str] = Field(
        None,
        description=(
            "Optional Jinja2-style boolean expression evaluated at runtime. "
            "If present, the edge is only traversed when the expression is truthy. "
            "Example: \"{{node_2.output.count > 0}}\""
        ),
    )

    @model_validator(mode="after")
    def no_self_loop(self) -> "WorkflowEdgeDSL":
        if self.source_id == self.target_id:
            raise ValueError(f"Self-loop detected on node '{self.source_id}'.")
        return self


# ─────────────────────────────────────────────────────────────────────────────
# ROOT DSL OBJECT
# ─────────────────────────────────────────────────────────────────────────────

class WorkflowDSL(BaseModel):
    """
    The canonical, executable DSL representation of a workflow.
    This object is stored as `dsl_json` in the `workflows` DB table
    and is the single source of truth for the execution engine.
    """
    id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Workflow UUID (auto-generated if omitted)",
    )
    name: str = Field(..., min_length=1, max_length=255)
    description: Optional[str] = None

    # ── DSL Versioning (RFC-002 §4) ──────────────────────────────────────────
    # version is bumped by WorkflowMutationService on every accepted patch.
    # migration_version is bumped only when the DSL shape itself changes.
    # compiler_version lets the engine reject DSLs built for an incompatible schema.
    version: int = Field(default=1, ge=1)
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="When this DSL was first created.",
    )
    updated_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="When this DSL was last mutated (bumped by WorkflowMutationService).",
    )
    migration_version: int = Field(
        default=1,
        ge=1,
        description="Incremented when the DSL shape changes in a backward-incompatible way.",
    )
    compiler_version: str = Field(
        default="1.0.0",
        description="Engine compiler version this DSL was built for.",
    )

    industry: Optional[str] = Field(None, description="Industry context, e.g. 'healthcare'")
    trigger: TriggerConfig
    nodes: List[WorkflowNodeDSL] = Field(..., min_length=1)
    edges: List[WorkflowEdgeDSL] = Field(default_factory=list)

    # Metadata
    tags: List[str] = Field(default_factory=list)
    variables: Dict[str, Any] = Field(
        default_factory=dict,
        description="Workflow-level variables available as {{vars.key}} in all nodes",
    )

    @model_validator(mode="after")
    def validate_graph_references(self) -> "WorkflowDSL":
        """Ensure all edge references point to existing node IDs."""
        node_ids = {n.id for n in self.nodes}

        for edge in self.edges:
            if edge.source_id not in node_ids:
                raise ValueError(
                    f"Edge references unknown source node '{edge.source_id}'. "
                    f"Known nodes: {sorted(node_ids)}"
                )
            if edge.target_id not in node_ids:
                raise ValueError(
                    f"Edge references unknown target node '{edge.target_id}'. "
                    f"Known nodes: {sorted(node_ids)}"
                )

        # Validate on_success / on_failure references
        for node in self.nodes:
            if node.on_success and node.on_success not in node_ids:
                raise ValueError(
                    f"Node '{node.id}' has on_success='{node.on_success}' "
                    f"which does not exist."
                )
            if node.on_failure and node.on_failure not in node_ids:
                raise ValueError(
                    f"Node '{node.id}' has on_failure='{node.on_failure}' "
                    f"which does not exist."
                )

        return self

    @model_validator(mode="after")
    def validate_trigger_node(self) -> "WorkflowDSL":
        """Ensure exactly one trigger node exists."""
        trigger_nodes = [n for n in self.nodes if n.type == NodeType.trigger]
        if len(trigger_nodes) != 1:
            raise ValueError(
                f"Workflow must have exactly 1 trigger node, found {len(trigger_nodes)}."
            )
        return self

    @model_validator(mode="after")
    def validate_no_duplicate_node_ids(self) -> "WorkflowDSL":
        ids = [n.id for n in self.nodes]
        dupes = {i for i in ids if ids.count(i) > 1}
        if dupes:
            raise ValueError(f"Duplicate node IDs found: {dupes}")
        return self

    def to_db_dict(self) -> dict:
        """Serialize to a plain dict suitable for storing in JSONB."""
        return self.model_dump(mode="json")
